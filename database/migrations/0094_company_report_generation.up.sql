CREATE OR REPLACE FUNCTION hse_report_delivery_provenance_guard()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='UPDATE' AND (
    NEW.report_id IS DISTINCT FROM OLD.report_id OR NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
    OR NEW.requested_by IS DISTINCT FROM OLD.requested_by
    OR NEW.requested_by_membership_id IS DISTINCT FROM OLD.requested_by_membership_id
    OR NEW.report_type IS DISTINCT FROM OLD.report_type OR NEW.format IS DISTINCT FROM OLD.format
    OR NEW.requested_at IS DISTINCT FROM OLD.requested_at OR NEW.request_scope IS DISTINCT FROM OLD.request_scope
    OR NEW.snapshot_rows IS DISTINCT FROM OLD.snapshot_rows OR NEW.schedule_at IS DISTINCT FROM OLD.schedule_at
    OR NEW.delivery_key IS DISTINCT FROM OLD.delivery_key OR NEW.created_at IS DISTINCT FROM OLD.created_at
  ) THEN
    RAISE EXCEPTION 'Report request provenance is immutable' USING ERRCODE='55000';
  END IF;
  IF TG_OP='UPDATE' AND OLD.status='delivered' AND (
    NEW.status IS DISTINCT FROM OLD.status OR NEW.artifact_key IS DISTINCT FROM OLD.artifact_key
    OR NEW.artifact_sha256 IS DISTINCT FROM OLD.artifact_sha256 OR NEW.artifact_byte_size IS DISTINCT FROM OLD.artifact_byte_size
    OR NEW.artifact_mime_type IS DISTINCT FROM OLD.artifact_mime_type OR NEW.generated_at IS DISTINCT FROM OLD.generated_at
    OR NEW.generation_job_id IS DISTINCT FROM OLD.generation_job_id OR NEW.generation_version IS DISTINCT FROM OLD.generation_version
  ) THEN
    RAISE EXCEPTION 'Delivered report artifact provenance is immutable' USING ERRCODE='55000';
  END IF;
  IF TG_OP='INSERT' OR NEW.generation_job_id IS DISTINCT FROM OLD.generation_job_id THEN
    IF NEW.report_id !~ '^report_[A-Za-z0-9_-]{3,80}$'
      OR NEW.requested_by_membership_id IS NULL OR NEW.requested_at IS NULL
      OR NEW.request_scope IS NULL OR NEW.snapshot_rows IS NULL OR NEW.generation_job_id IS NULL
      OR NOT EXISTS (
        SELECT 1 FROM auth_tenant_memberships memberships
        WHERE memberships.membership_id=NEW.requested_by_membership_id
          AND memberships.tenant_id=NEW.tenant_id AND memberships.account_id=NEW.requested_by
          AND memberships.portal_role='company'
      ) OR NOT EXISTS (
        SELECT 1 FROM platform_outbox_jobs jobs
        WHERE jobs.job_id=NEW.generation_job_id AND jobs.job_type='report.generation'
          AND jobs.status='pending' AND jobs.schema_version=1
          AND jobs.tenant_id=NEW.tenant_id AND jobs.membership_id=NEW.requested_by_membership_id
          AND jobs.enqueued_by_account_id=NEW.requested_by AND jobs.enqueued_by_role='company'
          AND jobs.payload=jsonb_build_object('reportRef',NEW.report_id)
      ) THEN
      RAISE EXCEPTION 'Report generation provenance is invalid' USING ERRCODE='55000';
    END IF;
    IF TG_OP='UPDATE' AND (
      OLD.status='delivered' OR NEW.status<>'queued' OR NEW.generation_version<>OLD.generation_version+1
      OR NOT EXISTS (SELECT 1 FROM platform_outbox_jobs jobs WHERE jobs.job_id=OLD.generation_job_id AND jobs.status='terminal_failed')
    ) THEN
      RAISE EXCEPTION 'Report retry is invalid' USING ERRCODE='55000';
    END IF;
  ELSIF NEW.generation_version IS DISTINCT FROM OLD.generation_version THEN
    RAISE EXCEPTION 'Report generation provenance is invalid' USING ERRCODE='55000';
  END IF;
  RETURN NEW;
END; $$;

CREATE TRIGGER report_delivery_provenance_guard BEFORE INSERT OR UPDATE ON report_deliveries
FOR EACH ROW EXECUTE FUNCTION hse_report_delivery_provenance_guard();
